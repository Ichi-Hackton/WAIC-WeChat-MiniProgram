/**
 * 红线安全护栏 —— Agent.md 第 6 节"绝对红线与伦理规则"落地
 *
 * 发送前对用户输入做关键词预检（第一道防线，模型侧 system-prompt 为第二道防线）：
 *  - block  体罚/强烈负面情绪 → 本地直接返回情绪安抚+正面管教话术，不请求模型，
 *          绝不顺从不当想法（红线 6.2）
 *  - inject 医疗诊断倾向（6.3）/ 隐私敏感（6.1）→ 注入上下文指令，
 *          要求模型按红线规范输出（免责声明/隐私提醒）
 *  - pass   正常放行
 *
 * 注意：正则经过防误伤设计——"孩子打架了怎么跟家长说"“爱打人的孩子怎么引导"
 * 等正当咨询不会触发 block；仅命中"想打/想骂/罚站"等指向性行为或强烈负面情绪才拦截。
 */

const PUNISH_PATTERNS = [
  /想打/, /想揍/, /想骂/, /想掐/, /想吼他/, /想动手/,
  /气死我/, /气死了/, /被.{0,6}气疯/, /快被.{0,6}气死/,
  /熊孩子/, /忍无可忍/, /忍不住想/,
  /罚站/, /关(?:进|到)?小黑屋/, /不许.{0,4}吃饭/, /不许.{0,4}喝水/,
  /体罚/, /冷暴力/,
  /打(他|她|他们|她们|这个|那个|一顿)/, /骂(他|她|他们|她们)一顿/,
  /收拾(他|她|这个孩子|那个孩子)/
]

const MEDICAL_PATTERNS = [
  /自闭症/, /孤独症/, /多动症/, /注意缺陷/, /发育迟缓/, /发育落后/,
  /感统失调/, /语言障碍/, /语言发育迟/, /智力低下/, /阿斯伯格/, /抽动症/
]

const PRIVACY_PATTERNS = [
  /身份证/, /家庭住址/, /详细住址/, /门牌号/,
  /正脸(?:照片|照|清晰)/, /全身照/, /没有打码/, /未打码/
]

/** 情绪安抚 + 正面管教引导（红线 6.2 的本地响应，Markdown 格式） */
const SOOTHE_REPLY = `亲爱的老师，先给您一个大大的拥抱🤗

带班时遇到让人头疼的时刻，有情绪太正常了——**您愿意把情绪说出来而不是憋着，已经是很棒的自我觉察了**。处理同伴冲突、应对哭闹确实很考验耐心，您每天都很努力，辛苦了。

先别急着处理孩子，**我们一起先深呼吸三次**，然后您可以试试这些科学的"冷处理 + 正面管教"方法：

1. **暂离现场 30 秒**：如果条件允许，请配班老师帮忙照看片刻，自己去喝口水、平复一下，情绪稳定后再介入
2. **冷处理**：孩子的不当行为若不会造成伤害，可以先降低回应强度，避免负面情绪互相强化
3. **正面管教句式**：用"老师看到你……（描述具体行为），我希望你……（明确期待）"代替评价和指责
4. **事后单独沟通**：等孩子情绪平复后，再引导他说一说发生了什么、还可以怎么做

如果方便，您可以跟我说说**具体发生了什么事、孩子的行为表现是什么**，我来帮您一起分析行为背后的原因，找几个更省心又科学的具体应对办法，好吗？

您已经做得很好了，也请一定照顾好自己哦💪`

/** 医疗类注入指令（红线 6.3） */
const MEDICAL_INJECTION = {
  type: 'medical',
  instruction: '【系统安全提示】用户消息涉及疑似发育障碍类话题。本次回复中你只能提供日常观察建议和家园沟通策略，绝对不要给出任何诊断性结论或倾向性判断；回复中必须原样包含以下声明："我提供的建议仅供参考，不能替代专业医疗机构的诊断，建议及时寻求专业医生的帮助。"'
}

/** 隐私类注入指令（红线 6.1） */
const PRIVACY_INJECTION = {
  type: 'privacy',
  instruction: '【系统安全提示】用户消息涉及幼儿敏感个人信息或影像资料。本次回复中你必须温和提醒（自然融入回复开头）："为了保护宝贝的隐私，建议您上传照片时对面部进行打码，或仅拍摄作品/背影哦。"不要记录、复述或要求用户补充这些敏感信息，涉及具体幼儿一律用"宝贝"代指。'
}

function matchAny(patterns, text) {
  return patterns.some((p) => p.test(text))
}

/**
 * 预检用户输入
 * @param {string} text 用户最新一条消息
 * @returns {{action: 'block'|'inject'|'pass', localReply?: string, injections?: Array}}
 */
function inspect(text) {
  const t = String(text || '')
  if (!t) return { action: 'pass' }

  // 最高优先级：体罚/强烈负面情绪 → 本地拦截（红线 6.2）
  if (matchAny(PUNISH_PATTERNS, t)) {
    return { action: 'block', localReply: SOOTHE_REPLY }
  }

  // 医疗诊断倾向（红线 6.3）与隐私敏感（红线 6.1）→ 注入指令
  const injections = []
  if (matchAny(MEDICAL_PATTERNS, t)) injections.push(MEDICAL_INJECTION)
  if (matchAny(PRIVACY_PATTERNS, t)) injections.push(PRIVACY_INJECTION)
  if (injections.length) return { action: 'inject', injections }

  return { action: 'pass' }
}

module.exports = {
  inspect,
  SOOTHE_REPLY
}
