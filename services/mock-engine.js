/* ==================== 意图识别 ==================== */

function detectIntent(text) {
  const t = String(text || '')
  const age = (t.match(/小班|中班|大班/) || [])[0]
  const domain = (t.match(/健康|语言|社会|科学|艺术/) || [])[0]

  if (/教案|活动设计|周计划|课程设计/.test(t)) {
    const topicMatch = t.match(/主题[是为：:]?\s*["'\u2018\u201C「]?([^"'\u2019\u201D」',，。.;;;；;！!？?\s]{1,20})/)
    return { type: 'lesson', age, domain, topic: topicMatch ? topicMatch[1] : null, len: t.length }
  }
  if (/观察|白描|行为记录/.test(t)) {
    return { type: 'observation', age, len: t.length }
  }
  if (/评语|期末评价|成长手册/.test(t)) {
    return { type: 'comment', age, len: t.length }
  }
  if (/入园焦虑|分离焦虑/.test(t)) {
    return { type: 'anxiety', age: age || '小班', len: t.length }
  }
  if (/家长|沟通|怎么.{0,6}说|告状|磕碰|打架|冲突|受伤|抓伤|投诉/.test(t)) {
    return { type: 'communication', age, len: t.length }
  }
  if (/环创|环境创设|教玩具|教具|手工|废旧|纸箱|纸盘|纸杯|变废为宝/.test(t)) {
    return { type: 'envdesign', age, material: /纸箱|瓶|罐|布|纸盘|纸杯/.test(t), len: t.length }
  }
  return { type: 'general', len: t.length }
}

