/* ==================== 响应与流式输出 ==================== */

function buildReply(messages, injections) {
  // 注入类红线优先响应（医疗/隐私）
  if (injections && injections.some((i) => i.type === 'medical')) return medicalReply()
  if (injections && injections.some((i) => i.type === 'privacy')) return privacyReply()

  const lastUser = [...messages].reverse().find((m) => m.role === 'user')
  const intent = detectIntent(lastUser ? lastUser.content : '')

  switch (intent.type) {
    case 'lesson':
      if (intent.age && intent.domain && (intent.topic || intent.len >= 30)) return lessonFull(intent)
      return lessonAsk(intent)
    case 'observation':
      if (intent.age && intent.len >= 25) return observationFull(intent)
      return observationAsk()
    case 'comment':
      if (intent.age && intent.len >= 25) return commentFull(intent)
      return commentAsk()
    case 'anxiety':
      return anxietyFull()
    case 'communication':
      if (intent.len >= 15) return communicationFull()
      return communicationAsk()
    case 'envdesign':
      if (intent.age && intent.material) return envdesignFull(intent)
      return envdesignAsk(intent)
    default:
      return generalReply()
  }
}

/** 模拟流式输出：定时器逐段回调，返回可 abort 的句柄 */
function streamOut(text, { onDelta, onDone }) {
  let idx = 0
  const STEP = 3
  const timer = setInterval(() => {
    if (idx >= text.length) {
      clearInterval(timer)
      onDone && onDone(text)
      return
    }
    const end = Math.min(idx + STEP, text.length)
    const chunk = text.slice(idx, end)
    idx = end
    onDelta && onDelta(chunk, text.slice(0, idx))
  }, 40)
  return {
    abort() {
      clearInterval(timer)
    }
  }
}

function respond(messages, injections, callbacks) {
  const text = buildReply(messages, injections)
  return streamOut(text, callbacks)
}

