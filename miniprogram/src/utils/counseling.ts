/**
 * 危機詞正則：自傷 / 自殺 / 輕生類表達（簡繁並列）
 *
 * 取向：核心信號從嚴收錄，允許適度誤報——觸發的是「溫柔關懷 + 求助
 * 熱線」而非阻斷，誤報成本僅為多一次真誠的關心；但「解脫 / 累 / 煩」
 * 等高歧義詞不收錄，避免泛濫稀釋。
 */
const CRISIS_RE =
  /不想活|活不下去|活[著着]沒[有意價值意味]|沒有活下去|想不開|想不开|自殺|自杀|自殘|自残|輕生|轻生|結束(自己的)?生命|结束(自己的)?生命|了結自己|了结自己|[傷伤]害自己|想消失/;

/**
 * 判定訊息是否含危機信號
 *
 * @param text 用戶輸入文本
 * @returns true 表示應立即觸發危機關懷（固定安撫文案 + 心理援助熱線）
 */
export function isCrisisMessage(text: string): boolean {
  return CRISIS_RE.test(text);
}
