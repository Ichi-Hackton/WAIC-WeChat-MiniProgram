/**
 * 急症詞正則：危及生命或需立即處置的表達（簡繁並列）
 *
 * 取向：核心急症信號從嚴收錄，允許適度誤報（如焦慮性胸悶也被善意引導
 * 就診）；但急症短路是整輪對話直接切換為 120 引導（不再回應原問題），
 * 故詞表對子串誤傷敏感——「中風」等歧義子串以負向環視排除高頻非醫療
 * 後綴（「命中風險」「家中風扇」類）；
 * 「中毒」不單獨收錄（「電腦中毒」類比喻會誤傷），僅收具體中毒語義；
 * 「頭暈」屬普通症狀（分診域），與「暈過去」（昏厥，急症）明確區分。
 */
const EMERGENCY_RE =
  /胸[痛悶闷]|呼吸困[難难]|喘不上[氣气]|喘不過[氣气]|大出血|出血不止|血流不止|意[識识]不清|昏迷|叫不醒|失去意[識识]|[暈晕][過过]去|抽搐|[驚惊]厥|突發中[風风]|中[風风](?![險险扇機机])|口角歪斜|嘴歪|半[邊边][無无]力|肢[體体][無无]力|言[語语]不清|[說说]不出[話话]|[誤误]服|[誤误]食|[藥药]物中毒|食物中毒|煤[氣气]中毒|[過过]敏性休克|喉[頭头]水[腫肿]/;

/**
 * 判定訊息是否含急症信號
 *
 * @param text 用戶輸入文本
 * @returns true 表示應立即短路到急診引導文案（120 / 保持鎮靜 / 陪同）
 */
export function isEmergencyMessage(text: string): boolean {
  return EMERGENCY_RE.test(text);
}

/**
 * 急症短路文案（rule-planner 命中急症詞時直接以 message 收斂，不走任何
 * SKILL——與心理危機短路同構：本地靜態文案，確定性可控）
 *
 * 與雲端 skill-health.ts 的 EMERGENCY_GUARD_REPLY 同主題不同載體：此處
 * 為規劃層文案（空 tasks + message 走 NEEDS_INPUT 收斂，狀態機零改動），
 * 雲端為 SKILL 端點回應；兩處要點（120 / 不自行開車 / FAST / 陪同）應
 * 保持一致，修改時同步。
 */
export const EMERGENCY_PROMPT =
  '你描述的情況可能需要緊急處理，請立即行動：\n' +
  '· 撥打 120 急救電話（或讓身邊的人立刻撥打），接通後簡明描述症狀與所在位置\n' +
  '· 保持鎮靜，就地休息，不要獨自走動或自行開車前往醫院\n' +
  '· 若患者意識不清，協助側臥防嗆咳，保持呼吸道通暢；切勿餵水餵藥\n' +
  '· 若出現口角歪斜 / 肢體無力 / 言語不清，牢記中風識別要點，越快送醫恢復越好\n' +
  '· 有陪同者時，請 TA 記下症狀開始時間與變化，告知醫生；並儘快通知家人\n' +
  '此時請以 120 與急診醫生的指引為準。';
